// SIGNS NEXTBLOCK'S MANIFEST VERSION 9 (bitcoin-arena kanban #2694, follow-up of #2655 option 2): version 8 in every term - core 7d197042,
// its bundle and the game's mark - under a new game id whose rule is that a staked run plays the liquidations its committee attests and no
// others (the registration's attestedLiquidations, the Arena's known-games entry). Its parent is version 8. Writes plugin/nextblock-v9.js
// and plugin/known-v9.js, both generated, public bytes only.
//   node tools/sign-manifest-v9.mjs <dev dir holding game-dev.pkcs8>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_V8, GAME_ID_V8 } from '../plugin/nextblock-v8.js';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

/** Version 9's terms, unsigned: version 8's with its version and parent. */
export function manifestV9Body() {
  const { signature, ...v8body } = MANIFEST_V8;
  void signature;
  return { ...v8body, version: MANIFEST_V8.version + 1, parentManifestId: GAME_ID_V8 };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [dir] = process.argv.slice(2);
  if (!dir) { console.error('usage: node sign-manifest-v9.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
  const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
  if (toHex(dev.pubkey) !== toHex(MANIFEST_V8.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V8.gameDevPubkey).slice(0, 16)}`);
  const body = manifestV9Body();
  const manifest = signManifest(body, dev);
  const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V8) ? MANIFEST_V8 : null) });
  if (!stands.ok) throw new Error(stands.why);
  const id = toHex(gameIdOf(manifest));
  writeFileSync(new URL('../plugin/nextblock-v9.js', import.meta.url), `// GENERATED by tools/sign-manifest-v9.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 9: version 8 (${toHex(GAME_ID_V8)}) in every term, under a new id whose staked run plays the
// liquidations its committee attests (bitcoin-arena kanban #2694). Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V8 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V9_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V9 = decodeManifest(fromHex(MANIFEST_V9_HEX));
export const GAME_ID_V9 = gameIdOf(MANIFEST_V9);
/** What a launcher loads from this module (ARENA_APPS): the registration - its staked runs take the committee's attested strikes only. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V9, gameId: GAME_ID_V9, cores: NEXTBLOCK_CORES_V8, attestedLiquidations: true });
`);
  writeFileSync(new URL('../plugin/known-v9.js', import.meta.url), `// GENERATED by tools/sign-manifest-v9.mjs. WHAT A CLIENT LISTS OF NEXTBLOCK VERSION 9: its signed bytes, the configs it plays as one world
// per round, and its rule: a staked run takes the committee's attested liquidations (bitcoin-arena kanban #2694).
//
//   node packages/arena-protocol/tools/known-games.js packages/nextblock/plugin/known-v9.js
import { MANIFEST_V9_HEX } from './nextblock-v9.js';
import { NEXTBLOCK_CORES_V8 } from './truck-cores.js';

export const KNOWN_GAME = Object.freeze({
  manifestHex: MANIFEST_V9_HEX,
  sharedWorld: [...new Set([...NEXTBLOCK_CORES_V8.values()].flatMap((c) => [...c.configs].filter(([, cfg]) => cfg && cfg.worldShared).map(([h]) => h)))],
  attestedLiquidations: true,
});
`);
  console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V8).slice(0, 16)}, ${body.cores.length} cores, ${body.clients.length} clients, game_id ${id}`);
}
